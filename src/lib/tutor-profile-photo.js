// eslint-disable-next-line @typescript-eslint/no-require-imports -- Node tests import this CommonJS helper directly.
const sharp = require('sharp')

const TUTOR_PHOTO_MAX_BYTES = 5 * 1024 * 1024
const TUTOR_PHOTO_MAX_PIXELS = 25_000_000
const TUTOR_PHOTO_MAX_DIMENSION = 1600
const TUTOR_PHOTO_PUBLIC_ORIGIN = 'https://fceekjlispfjduetumrf.supabase.co'
const TUTOR_PHOTO_PUBLIC_PREFIX = '/storage/v1/object/public/tutor-photos/'

const MIME_FORMATS = {
  'image/jpeg': { format: 'jpeg', extension: 'jpg' },
  'image/png': { format: 'png', extension: 'png' },
  'image/webp': { format: 'webp', extension: 'webp' },
  'image/avif': { format: 'heif', extension: 'avif' },
}

/**
 * Decode the entire image with libvips, cap its pixel count and output size,
 * and re-encode it. This rejects truncated/polyglot pseudo-images and strips
 * untrusted metadata before the result reaches public Storage.
 */
async function processTutorPhoto(mimeType, bytes) {
  const expected = MIME_FORMATS[mimeType]
  if (!expected || !bytes?.length || bytes.length > TUTOR_PHOTO_MAX_BYTES) return null

  try {
    const image = sharp(bytes, {
      failOn: 'error',
      limitInputPixels: TUTOR_PHOTO_MAX_PIXELS,
      sequentialRead: true,
    })
    const metadata = await image.metadata()
    if (metadata.format !== expected.format || !metadata.width || !metadata.height) return null
    if (metadata.width * metadata.height > TUTOR_PHOTO_MAX_PIXELS) return null

    const resized = image
      .rotate()
      .resize({
        width: TUTOR_PHOTO_MAX_DIMENSION,
        height: TUTOR_PHOTO_MAX_DIMENSION,
        fit: 'inside',
        withoutEnlargement: true,
      })

    let output
    if (mimeType === 'image/jpeg') output = resized.jpeg({ quality: 88, mozjpeg: true })
    else if (mimeType === 'image/png') output = resized.png({ compressionLevel: 9 })
    else if (mimeType === 'image/webp') output = resized.webp({ quality: 88 })
    else output = resized.avif({ quality: 60 })

    const data = await output.toBuffer()
    return {
      bytes: data,
      contentType: mimeType,
      extension: expected.extension,
    }
  } catch {
    return null
  }
}

/**
 * Return a Storage object path only for URLs generated by this project and
 * nested directly beneath the authenticated user's namespace.
 */
function ownedTutorPhotoPath(photoUrl, ownerUserId) {
  if (typeof photoUrl !== 'string' || typeof ownerUserId !== 'string') return null

  try {
    const url = new URL(photoUrl)
    if (url.origin !== TUTOR_PHOTO_PUBLIC_ORIGIN || url.search || url.hash) return null
    if (!url.pathname.startsWith(TUTOR_PHOTO_PUBLIC_PREFIX)) return null

    const path = url.pathname.slice(TUTOR_PHOTO_PUBLIC_PREFIX.length)
    const ownerPrefix = `${ownerUserId}/`
    if (!path.startsWith(ownerPrefix)) return null

    const fileName = path.slice(ownerPrefix.length)
    if (!/^[0-9a-f-]{36}\.(?:jpg|png|webp|avif)$/i.test(fileName)) return null
    return `${ownerPrefix}${fileName}`
  } catch {
    return null
  }
}

module.exports = {
  TUTOR_PHOTO_MAX_BYTES,
  TUTOR_PHOTO_MAX_DIMENSION,
  TUTOR_PHOTO_MAX_PIXELS,
  ownedTutorPhotoPath,
  processTutorPhoto,
}
